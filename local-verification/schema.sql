-- Verification schema derived from the committed JPA mappings.
-- This is a local test fixture, not an original project migration.
CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(100) NOT NULL, email varchar(255) NOT NULL UNIQUE,
 password_hash varchar(255) NOT NULL, status varchar(20) NOT NULL,
 created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE resources (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_type_id bigint NOT NULL, name varchar(100) NOT NULL,
 description varchar(255), capacity integer NOT NULL CHECK(capacity > 0),
 status varchar(20) NOT NULL, location varchar(255),
 created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL
);
CREATE TABLE availability_slots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_id bigint NOT NULL REFERENCES resources(id),
 start_time timestamp(6) NOT NULL, end_time timestamp(6) NOT NULL,
 capacity integer NOT NULL CHECK(capacity > 0),
 available_capacity integer NOT NULL CHECK(available_capacity >= 0 AND available_capacity <= capacity),
 status varchar(20) NOT NULL, created_at timestamp(6) NOT NULL,
 updated_at timestamp(6) NOT NULL, CHECK(end_time > start_time)
);
CREATE TABLE bookings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_reference varchar(50) NOT NULL UNIQUE,
 user_id bigint NOT NULL REFERENCES users(id), slot_id bigint NOT NULL REFERENCES availability_slots(id),
 quantity integer NOT NULL CHECK(quantity > 0), status varchar(20) NOT NULL,
 expires_at timestamp(6), created_at timestamp(6) NOT NULL
);
CREATE TABLE idempotency_keys (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id), key varchar(255) NOT NULL,
 request_hash varchar(255) NOT NULL, booking_id bigint REFERENCES bookings(id),
 status varchar(255) NOT NULL, created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at timestamp(6) NOT NULL, CONSTRAINT uk_idempotency_user_key UNIQUE(user_id,key)
);
CREATE TABLE outbox_events (
 id uuid PRIMARY KEY, aggregate_type varchar(50) NOT NULL,
 aggregate_id bigint NOT NULL, event_type varchar(100) NOT NULL,
 payload jsonb NOT NULL, status varchar(20) NOT NULL,
 created_at timestamp(6) NOT NULL, published_at timestamp(6)
);
CREATE TABLE processed_events (
 event_id uuid PRIMARY KEY, event_type varchar(100) NOT NULL,
 processed_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX slots_resource_idx ON availability_slots(resource_id);
CREATE INDEX bookings_user_idx ON bookings(user_id);
CREATE INDEX outbox_pending_idx ON outbox_events(created_at) WHERE status='PENDING';
